REPO = Path(__file__).resolve().parents[2]
PROFILE_DIR = REPO / "eval" / "config" / "ladder"
LANE_DIR = REPO / "eval" / "config" / "lanes"
# evaluator sections a ladder profile may pin (deep-merged over the base lane)
LANE_OVERRIDE_KEYS = ("spectra", "spectra_ecmwf", "tc", "probabilistic")
CKPT_STEP_RE = re.compile(r"step[_=]?(\d+)")


def derive_lane(prof: dict) -> str:
    """Materialise a `base:`-inheriting lane variant carrying the profile's pinned
    evaluator knobs, and return its NAME.

    `eval.cli --lane` resolves a name inside eval/config/lanes/, so profile-level
    evaluator overrides (cheap spectra, in particular) cannot reach the evaluators
    any other way. The lane loader deep-merges over `base`, so only the pinned keys
    need to appear here -- everything else (truth caches, storm boxes, predict
    settings) is inherited. Deterministic: rewritten only when the content changes.
    """
    over = {k: prof[k] for k in LANE_OVERRIDE_KEYS if k in prof}
    if not over:
        return prof["lane"]
    name = f"_ladder_{prof['card_id']}"
    text = (f"# GENERATED by eval.jobs.ladder from ladder profile '{prof['_name']}'.\n"
            "# Do not hand-edit -- edit the profile and re-run `ladder score`.\n"
            "# Exists so the ladder's pinned evaluator knobs reach eval.cli, which takes\n"
            "# a lane NAME; the lane loader deep-merges this over `base`.\n"
            + yaml.safe_dump({"base": prof["lane"], **over}, sort_keys=False))
    p = LANE_DIR / f"{name}.yaml"
    if not p.exists() or p.read_text() != text:
        p.write_text(text)
        print(f"ladder: wrote derived lane {p.name} (overrides: {', '.join(over)})")
    return name


# --------------------------------------------------------------------------- profiles
def load_profile(name: str) -> dict:
    # accept either a registered profile name or a direct path to a profile YAML
    p = Path(name) if name.endswith(".yaml") else PROFILE_DIR / f"{name}.yaml"
    if not p.exists():
        raise SystemExit(f"ladder: unknown profile '{name}' (expected {p})")
    name = p.stem
    prof = yaml.safe_load(p.read_text())
    prof["_name"] = name
    # resolvable handle for the sbatch: a registered profile keeps its name, an
    # out-of-repo YAML must travel as its absolute path
    prof["_ref"] = name if p.parent == PROFILE_DIR else str(p.resolve())
    for key in ("card_id", "lane", "host", "bundle_dir", "budget"):
        if key not in prof:
            raise SystemExit(f"ladder: profile '{name}' missing key '{key}'")
    return prof


def ladder_paths(prof: dict) -> dict:
    perm = Path(prof.get("perm_root", "/home/ecm5702/perm")) / "eval-ladders" / prof["card_id"]
    scratch = Path(prof.get("scratch_root", "/home/ecm5702/scratch")) / "eval" / "ladder" / prof["card_id"]
    return {"perm": perm, "scratch": scratch, "json": perm / "ladder.json", "png": perm / "ladder.png"}


def load_ladder(prof: dict) -> dict:
    jp = ladder_paths(prof)["json"]
    if jp.exists():
        return json.loads(jp.read_text())
    return {
        "schema_version": "1.0",
        "card_id": prof["card_id"],
        "lane": prof["lane"],
        "profile": prof["_name"],
        "profile_pins": {k: prof.get(k) for k in ("budget", "seed_draws", "spectra", "storm_box")},
        "note": "TC values at ladder budget = trend indicator, NOT a verdict (replica noise ±7/4.8 hPa).",
        "baselines": {},
        "rows": [],
        "loss": {},
    }


def save_ladder(prof: dict, ladder: dict) -> Path:
    jp = ladder_paths(prof)["json"]
    jp.parent.mkdir(parents=True, exist_ok=True)
    with tempfile.NamedTemporaryFile("w", dir=jp.parent, delete=False, suffix=".tmp") as f:
        json.dump(ladder, f, indent=1, sort_keys=True)
        tmp = f.name
    os.replace(tmp, jp)
    return jp


