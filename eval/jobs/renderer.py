"""HPC sbatch script renderer for the evaluation framework.

Generates sbatch scripts from YAML host/lane configuration.
Runnable as a module: ``python -m eval.jobs.renderer --help``
"""

from __future__ import annotations

import argparse
import shlex
import sys
from pathlib import Path
from typing import Any


def _checkpoint_short(path: str) -> str:
    """Extract a short identifier from a checkpoint path.

    If *path* ends with ``.ckpt``, use the parent directory name;
    otherwise use the file stem.  Truncated to 20 characters.
    """
    p = Path(path)
    if p.suffix == ".ckpt":
        name = p.parent.name
    else:
        name = p.stem
    return name[:20]


def _sbatch_header(
    lane: str,
    checkpoint: str,
    scheduler: dict[str, Any],
    scratch_root: str,
) -> str:
    """Render ``#SBATCH`` directive block."""
    short = _checkpoint_short(checkpoint)
    qos = scheduler["qos"]
    time_limit = scheduler.get("default_time", "04:00:00")
    mem = scheduler.get("default_mem", "64G")
    cpus = scheduler.get("default_cpus", 16)
    slurm_out = f"{scratch_root}/eval/_slurm/%x_%j.out"

    lines = [
        "#!/bin/bash",
        f"#SBATCH --job-name=eval-{lane}-{short}",
        f"#SBATCH --qos={qos}",
        f"#SBATCH --time={time_limit}",
        f"#SBATCH --mem={mem}",
        f"#SBATCH --cpus-per-task={cpus}",
        "#SBATCH --nodes=1",
        "#SBATCH --ntasks-per-node=1",
        f"#SBATCH --output={slurm_out}",
    ]
    return "\n".join(lines)


def _comment_block(lane: str, host: str, checkpoint: str, mode: str) -> str:
    """Render the informational comment block."""
    lines = [
        "",
        "set -euo pipefail",
        "",
        "# Generated by eval/jobs/renderer.py",
        f"# Lane: {lane}",
        f"# Host: {host}",
        f"# Checkpoint: {checkpoint}",
        f"# Mode: {mode}",
    ]
    return "\n".join(lines)


def _environment_block(
    environment_setup: dict[str, Any],
    code_root: str,
) -> str:
    """Render module loads, exports, PYTHONPATH, venv activation, and cd."""
    lines: list[str] = [""]

    # Module loads
    for mod in environment_setup.get("module_loads", []):
        lines.append(f"module load {mod}")

    lines.append("")

    # Exports from config
    for key, value in environment_setup.get("exports", {}).items():
        lines.append(f'export {key}="{value}"')

    # PYTHONPATH must include code_root
    lines.append(f'export PYTHONPATH="{code_root}:${{PYTHONPATH:-}}"')

    lines.append("")

    # Venv activation
    venv_activate = environment_setup["venv_activate"]
    lines.append(f"source {venv_activate}")

    lines.append("")

    # cd to code root
    lines.append(f"cd {code_root}")

    return "\n".join(lines)


def _cli_command(
    mode: str,
    checkpoint: str,
    lane: str,
    overrides: dict[str, Any] | None = None,
) -> str:
    """Render the ``python -m eval.cli`` invocation."""
    ckpt_quoted = shlex.quote(checkpoint)
    parts = [
        "",
        "# Run evaluation",
        f"python -m eval.cli {mode} \\",
        f"    --checkpoint {ckpt_quoted} \\",
    ]

    # Collect override flags
    override_parts: list[str] = []
    if overrides:
        for flag, value in overrides.items():
            if isinstance(value, bool) and value:
                override_parts.append(f"    {flag} \\")
            elif not isinstance(value, bool):
                override_parts.append(f"    {flag} {shlex.quote(str(value))} \\")

    # Add override lines
    for part in override_parts:
        parts.append(part)

    # Final line: --lane (no trailing backslash)
    parts.append(f"    --lane {lane}")

    return "\n".join(parts)


def render_sbatch(
    lane: str,
    host: str,
    checkpoint: str,
    mode: str = "run",
    overrides: dict[str, Any] | None = None,
    output_path: Path | None = None,
) -> str:
    """Generate an sbatch script from config.

    Parameters
    ----------
    lane : str
        Lane name (e.g. ``o96_o320``).
    host : str
        Host name (e.g. ``atos_ac``).
    checkpoint : str
        Path to the model checkpoint.
    mode : str
        CLI mode — one of ``run``, ``predict``, ``evaluate``.
    overrides : dict | None
        Extra CLI flags passed through to ``eval.cli``.
        Keys are flag names (e.g. ``--only``), values are either
        strings or ``True`` for boolean flags.
    output_path : Path | None
        If given, write the script to this path.

    Returns
    -------
    str
        The complete sbatch script content.
    """
    # Import here to keep module importable even if config is missing
    from eval.config.loader import load_host

    host_cfg = load_host(host)

    script = "\n".join([
        _sbatch_header(lane, checkpoint, host_cfg["scheduler"], host_cfg["scratch_root"]),
        _comment_block(lane, host, checkpoint, mode),
        _environment_block(host_cfg["environment_setup"], host_cfg["code_root"]),
        _cli_command(mode, checkpoint, lane, overrides),
        "",  # trailing newline
    ])

    if output_path is not None:
        output_path.parent.mkdir(parents=True, exist_ok=True)
        output_path.write_text(script, encoding="utf-8")

    return script


def _build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        prog="python -m eval.jobs.renderer",
        description="Generate sbatch scripts for the evaluation framework.",
    )
    parser.add_argument("--lane", required=True, help="Lane name (e.g. o96_o320)")
    parser.add_argument("--host", required=True, help="Host name (e.g. atos_ac)")
    parser.add_argument("--checkpoint", required=True, help="Path to model checkpoint")
    parser.add_argument(
        "--mode", default="run", choices=["run", "predict", "evaluate"],
        help="CLI mode (default: run)",
    )
    parser.add_argument("--output", default=None, help="Write script to this path")
    parser.add_argument(
        "--dry-run", action="store_true",
        help="Print script to stdout without writing",
    )
    parser.add_argument(
        "--only", default=None,
        help="Comma-separated evaluator list (passed through to eval.cli)",
    )
    parser.add_argument(
        "--include-diagnostics", action="store_true",
        help="Include weight diagnostics (passed through to eval.cli)",
    )
    return parser


def main(argv: list[str] | None = None) -> None:
    parser = _build_parser()
    args = parser.parse_args(argv)

    # Build overrides from pass-through flags
    overrides: dict[str, Any] = {}
    if args.only:
        overrides["--only"] = args.only
    if args.include_diagnostics:
        overrides["--include-diagnostics"] = True

    output_path = Path(args.output) if args.output and not args.dry_run else None

    script = render_sbatch(
        lane=args.lane,
        host=args.host,
        checkpoint=args.checkpoint,
        mode=args.mode,
        overrides=overrides if overrides else None,
        output_path=output_path,
    )

    print(script)


if __name__ == "__main__":
    main()
